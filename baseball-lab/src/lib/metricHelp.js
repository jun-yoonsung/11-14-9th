/** 말풍선에 보여 줄 내용: {meaning, how, dir}. 뜻이 없는 지표(새로 생긴 것)는 계산식만 보여 준다. */
export function tipOf(type, def) {
  const dir = def.better === "low" ? "낮을수록 좋아요" : def.better === "high" && def.group !== "누적 기록" && !["G", "D"].includes(def.key) ? "높을수록 좋아요" : "";   // 경기·등판 같은 누적 수는 좋고 나쁨이 없다
  return { meaning: (HELP[type] || {})[def.key] || "", how: def.how || "", dir };
}
